// Command gen-simplified writes internal/validate/simplified.txt, the list of
// characters that only Simplified Chinese uses, from two OpenCC dictionaries.
//
// Usage:
//
//	go run ./tools/gen-simplified STCharacters.txt TWVariants.txt > internal/validate/simplified.txt
//
// Both files are in data/dictionary/ of https://github.com/BYVoid/OpenCC
// (Apache-2.0). Each line of STCharacters.txt maps one Simplified character
// (the key) to its Traditional candidates. A key is kept unless
//
//   - its candidates include the key itself, which makes it a Traditional
//     character too (for example 后, 干 and 里), or
//   - it is a Taiwan standard form according to TWVariants.txt, whose values
//     are the Taiwan forms of variants (for example 群, 床 and 峰, which
//     OpenCC lists as Simplified forms of the variants 羣, 牀 and 峯), or
//   - it is in taiwanKept.
//
// Reporting those would flag valid zh-TW text.
package main

import (
	"bufio"
	"crypto/sha256"
	"fmt"
	"io"
	"os"
	"slices"
	"strings"
	"unicode/utf8"
)

// taiwanKept lists characters that OpenCC treats as the Simplified form of a
// variant, that TWVariants.txt does not cover, and that zh-TW text uses as
// they are.
var taiwanKept = map[rune]string{
	'秘': "秘密, 神秘; OpenCC maps it to the variant 祕",
	'霉': "發霉, 倒霉; the standard form, OpenCC maps it to the variant 黴",
	'肴': "佳肴; the standard form, OpenCC maps it to the variant 餚",
	'苧': "苧麻; the standard form, OpenCC maps it to the variant 薴",
}

func main() {
	if len(os.Args) != 3 {
		fmt.Fprintln(os.Stderr, "usage: gen-simplified STCharacters.txt TWVariants.txt > simplified.txt")
		os.Exit(2)
	}
	if err := generate(os.Args[1], os.Args[2], os.Stdout); err != nil {
		fmt.Fprintln(os.Stderr, "gen-simplified:", err)
		os.Exit(1)
	}
}

func generate(stPath, twPath string, w io.Writer) error {
	st, err := os.ReadFile(stPath)
	if err != nil {
		return err
	}
	tw, err := os.ReadFile(twPath)
	if err != nil {
		return err
	}
	chars, err := simplifiedOnly(string(st), string(tw))
	if err != nil {
		return err
	}
	if len(chars) == 0 {
		return fmt.Errorf("%s: no characters found, is it OpenCC's STCharacters.txt?", stPath)
	}

	bw := bufio.NewWriter(w)
	fmt.Fprintf(bw, "# Characters used only in Simplified Chinese, one per line, in code point order.\n")
	fmt.Fprintf(bw, "# Generated by tools/gen-simplified; do not edit by hand.\n")
	fmt.Fprintf(bw, "#\n")
	fmt.Fprintf(bw, "# Source: OpenCC (https://github.com/BYVoid/OpenCC, Apache-2.0), data/dictionary/\n")
	fmt.Fprintf(bw, "#   STCharacters.txt sha256 %x\n", sha256.Sum256(st))
	fmt.Fprintf(bw, "#   TWVariants.txt   sha256 %x\n", sha256.Sum256(tw))
	fmt.Fprintf(bw, "# A key of STCharacters.txt is listed unless its Traditional candidates include\n")
	fmt.Fprintf(bw, "# the key itself, TWVariants.txt lists it as a Taiwan form, or the generator\n")
	fmt.Fprintf(bw, "# keeps it (taiwanKept).\n")
	for _, c := range chars {
		fmt.Fprintf(bw, "%c\n", c)
	}
	return bw.Flush()
}

// entry is one line of an OpenCC dictionary.
type entry struct {
	key    rune
	values []string
}

// parseDict parses an OpenCC dictionary: "key<TAB>value value…" per line,
// with # comment lines and blank lines.
func parseDict(dict string) ([]entry, error) {
	var out []entry
	for i, line := range strings.Split(dict, "\n") {
		line = strings.TrimRight(line, "\r")
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		key, values, ok := strings.Cut(line, "\t")
		if !ok || strings.TrimSpace(values) == "" {
			return nil, fmt.Errorf("line %d: want \"key<TAB>candidates\", got %q", i+1, line)
		}
		c, size := utf8.DecodeRuneInString(key)
		if c == utf8.RuneError || size != len(key) {
			return nil, fmt.Errorf("line %d: key %q is not a single character", i+1, key)
		}
		out = append(out, entry{c, strings.Fields(values)})
	}
	return out, nil
}

// simplifiedOnly returns, sorted and without duplicates, the characters of
// the STCharacters dictionary st that only Simplified Chinese uses; tw is the
// TWVariants dictionary.
func simplifiedOnly(st, tw string) ([]rune, error) {
	stEntries, err := parseDict(st)
	if err != nil {
		return nil, fmt.Errorf("STCharacters: %w", err)
	}
	twEntries, err := parseDict(tw)
	if err != nil {
		return nil, fmt.Errorf("TWVariants: %w", err)
	}
	taiwanForms := map[string]bool{}
	for _, e := range twEntries {
		for _, v := range e.values {
			taiwanForms[v] = true
		}
	}

	var out []rune
	for _, e := range stEntries {
		key := string(e.key)
		_, kept := taiwanKept[e.key]
		if !slices.Contains(e.values, key) && !taiwanForms[key] && !kept {
			out = append(out, e.key)
		}
	}
	slices.Sort(out)
	return slices.Compact(out), nil
}
