// Learning thresholds.
const (
	// A field is an identifier everywhere when every counted occurrence is the
	// same in all three languages and there are at least this many of them.
	identifierMinCount = 3
	// A field is an identifier within a group of files when at least
	// groupMinPercent percent of at least groupMinCount occurrences are.
	groupMinCount   = 20
	groupMinPercent = 99
)

// header starts the generated rule file.
const header = "# Generated by `lct fields learn`. Do not edit; put manual rules in fields.manual.yaml.\n"

// Learned is the rules derived from the official packs, in the format of
// rules/fields.yaml.
type Learned struct {
	// IdentifierFields are the fields that are never translated, in any file.
	IdentifierFields []string `yaml:"identifier_fields" json:"identifier_fields"`
	// GroupFields maps a file group (see Group) to the fields that are never
	// translated in its files.
	GroupFields map[string][]string `yaml:"group_fields" json:"group_fields"`
}

// LoadLearned reads rules/fields.yaml. A missing file reads as no rules.
func LoadLearned(root string) (*Learned, error) {
	l := &Learned{}
	if _, err := decodeFile(filepath.Join(root, generatedFile), l, true); err != nil {
		return nil, err
	}
	if err := checkNames(generatedFile, "identifier_fields", l.IdentifierFields); err != nil {
		return nil, err
	}
	for g, names := range l.GroupFields {
		if g == "" {
			return nil, fmt.Errorf("fields: %s: group_fields has an empty group name", generatedFile)
		}
		if err := checkNames(generatedFile, "group_fields."+g, names); err != nil {
			return nil, err
		}
	}
	l.IdentifierFields = nonNil(l.IdentifierFields)
	if l.GroupFields == nil {
		l.GroupFields = map[string][]string{}
	}
	return l, nil
}

func nonNil(s []string) []string {
	if s == nil {
		return []string{}
	}
	return s
}

// counts is how often a field was seen with a value that is the same in KR,
// EN and JP, out of how often it was seen.
type counts struct{ same, total int }

type groupField struct{ group, field string }

// Learn derives the field rules from the three official packs. It looks at
// every file that all three packs have and counts the units whose KR text is
// not empty (see Classify) and has an aligned text in both EN and JP; a unit
// counts as identical when its KR, EN and JP texts are exactly equal.
//
//   - Layer 1: a field whose counted occurrences are all identical, at least
//     3 of them, is an identifier field.
//   - Layer 2: a group of files and a field where at least 99% of at least 20
//     counted occurrences are identical is a group field, unless the field is
//     already in layer 1.
//
// The result does not know the manual rules; use Without to drop what they
// already say.
func Learn(kr, en, jp *pack.Pack) (*Learned, error) {
	if kr == nil || en == nil || jp == nil {
		return nil, fmt.Errorf("fields: Learn needs the KR, EN and JP packs")
	}
	byField := make(map[string]*counts)
	byGroup := make(map[groupField]*counts)
	bump := func(c *counts, same bool) {
		c.total++
		if same {
			c.same++
		}
	}
	for _, file := range kr.Files() {
		if !en.Has(file) || !jp.Has(file) {
			continue
		}
		krDoc, err := kr.Doc(file)
		if err != nil {
			return nil, fmt.Errorf("fields: %w", err)
		}
		enDoc, err := en.Doc(file)
		if err != nil {
			return nil, fmt.Errorf("fields: %w", err)
		}
		jpDoc, err := jp.Doc(file)
		if err != nil {
			return nil, fmt.Errorf("fields: %w", err)
		}
		enAligned := align.AlignLang(file, krDoc, enDoc)
		jpAligned := align.AlignLang(file, krDoc, jpDoc)
		group := Group(file)
		for _, u := range units.Extract(file, krDoc) {
			if u.Field == "" || isEmptyValue(u.KR) {
				continue
			}
			e, okEN := enAligned[u.Pointer]
			j, okJP := jpAligned[u.Pointer]
			if !okEN || !okJP {
				continue
			}
			same := u.KR == e.Value && u.KR == j.Value
			bump(entry(byField, u.Field), same)
			bump(entry(byGroup, groupField{group, u.Field}), same)
		}
	}

	l := &Learned{IdentifierFields: []string{}, GroupFields: map[string][]string{}}
	isIdentifier := make(map[string]bool)
	for _, field := range slices.Sorted(maps.Keys(byField)) {
		c := byField[field]
		if c.total >= identifierMinCount && c.same == c.total {
			l.IdentifierFields = append(l.IdentifierFields, field)
			isIdentifier[field] = true
		}
	}
	for gf, c := range byGroup {
		if isIdentifier[gf.field] || c.total < groupMinCount || c.same*100 < c.total*groupMinPercent {
			continue
		}
		l.GroupFields[gf.group] = append(l.GroupFields[gf.group], gf.field)
	}
	for _, names := range l.GroupFields {
		slices.Sort(names)
	}
	return l, nil
}

// entry returns m[k], adding a zero value first if there is none.
func entry[K comparable](m map[K]*counts, k K) *counts {
	c := m[k]
	if c == nil {
		c = new(counts)
		m[k] = c
	}
	return c
}

// Without returns a copy of l minus what the manual rules already say: the
// fields of the manual identifier list (from both layers) and the manual
// group fields. The generated file then holds only what the manual file does
// not.
func (l *Learned) Without(manual *Rules) *Learned {
	out := &Learned{IdentifierFields: []string{}, GroupFields: map[string][]string{}}
	for _, f := range l.IdentifierFields {
		if !manual.identifiers[f] {
			out.IdentifierFields = append(out.IdentifierFields, f)
		}
	}
	for g, names := range l.GroupFields {
		for _, f := range names {
			if !manual.identifiers[f] && !manual.groupFields[g][f] {
				out.GroupFields[g] = append(out.GroupFields[g], f)
			}
		}
	}
	return out
}

// YAML returns the content of rules/fields.yaml for l. The lists are sorted,
// so the same rules always give the same bytes.
func (l *Learned) YAML() []byte {
	doc := Learned{
		IdentifierFields: sortedCopy(l.IdentifierFields),
		GroupFields:      map[string][]string{},
	}
	for g, names := range l.GroupFields {
		if len(names) > 0 {
			doc.GroupFields[g] = sortedCopy(names)
		}
	}
	var buf bytes.Buffer
	buf.WriteString(header)
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	// Encoding a struct of strings, string slices and a string map cannot fail.
	if err := enc.Encode(doc); err != nil {
		panic(err)
	}
	if err := enc.Close(); err != nil {
		panic(err)
	}
	return buf.Bytes()
}

func sortedCopy(s []string) []string {
	out := slices.Clone(s)
	if out == nil {
		out = []string{}
	}
	slices.Sort(out)
	return out
}

// Change is one rule that a new set of learned rules adds or removes.
type Change struct {
	Op    string `json:"op"`              // "add" or "remove"
	Group string `json:"group,omitempty"` // empty for an identifier field
	Field string `json:"field"`
}

// String formats c as one line, such as "+ identifier_fields: key" or
// "- group_fields: Skills.tag".
func (c Change) String() string {
	sign := "+"
	if c.Op == "remove" {
		sign = "-"
	}
	if c.Group == "" {
		return fmt.Sprintf("%s identifier_fields: %s", sign, c.Field)
	}
	return fmt.Sprintf("%s group_fields: %s.%s", sign, c.Group, c.Field)
}

// Diff lists what l adds to and removes from old: identifier fields first,
// then group fields, each sorted by group and field.
func (l *Learned) Diff(old *Learned) []Change {
	cur, prev := l.rules(), old.rules()
	all := make(map[groupField]bool, len(cur)+len(prev))
	for gf := range cur {
		all[gf] = true
	}
	for gf := range prev {
		all[gf] = true
	}
	keys := slices.SortedFunc(maps.Keys(all), func(a, b groupField) int {
		if c := strings.Compare(a.group, b.group); c != 0 {
			return c
		}
		return strings.Compare(a.field, b.field)
	})
	var changes []Change
	for _, gf := range keys {
		switch {
		case cur[gf] && !prev[gf]:
			changes = append(changes, Change{Op: "add", Group: gf.group, Field: gf.field})
		case prev[gf] && !cur[gf]:
			changes = append(changes, Change{Op: "remove", Group: gf.group, Field: gf.field})
		}
	}
	return changes
}

// rules flattens l into a set; an identifier field has an empty group.
func (l *Learned) rules() map[groupField]bool {
	set := make(map[groupField]bool)
	for _, f := range l.IdentifierFields {
		set[groupField{"", f}] = true
	}
	for g, names := range l.GroupFields {
		for _, f := range names {
			set[groupField{g, f}] = true
		}
	}
	return set
}
